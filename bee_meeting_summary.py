#!/usr/bin/env python3
"""
bee_meeting_summary.py — Acme Services
Pulls the last 10 hours of Bee wristband data, generates a meeting summary
and action items via Gemini, emails to Owner, and logs to Google Sheets.

Usage:
    python3 /home/user/bee_meeting_summary.py
    python3 /home/user/bee_meeting_summary.py --label "Q2 Planning Meeting"

Dependencies:
    - bee CLI (logged in via: bee login)
    - gog CLI (for email + sheets)
    - google-genai pip package
"""

import subprocess
import json
import sys
import os
import argparse
from datetime import datetime
from google import genai

# ── Configuration ─────────────────────────────────────────────────────────────

GEMINI_API_KEY   = "YOUR_GEMINI_API_KEY"
GEMINI_MODEL     = "gemini-2.5-flash"

EMAIL_FROM       = "bot@example.com"
EMAIL_TO         = "owner@example.com"          # Owner
EMAIL_CC         = ""                               # e.g. "manager1@example.com"

SHEET_ID         = "1G_bGEmeSTvObaFYmp9-gnmhCJZ10JvtqN82PJChBHHA"
SHEET_TAB        = "MeetingSummaries"
SHEET_ACCOUNT    = "owner@example.com"

GOG_PASSWORD     = "YOUR_GOG_KEYRING_PASSWORD"
GOG_BIN          = "/usr/local/bin/gog"

LOG_FILE         = "/home/user/bee_meeting_summary.log"

# ── Helpers ───────────────────────────────────────────────────────────────────

def log(msg):
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    line = f"[{ts}] {msg}"
    print(line)
    with open(LOG_FILE, "a") as f:
        f.write(line + "\n")


def run(cmd, env_extra=None):
    env = os.environ.copy()
    if env_extra:
        env.update(env_extra)
    result = subprocess.run(cmd, shell=True, capture_output=True, text=True, env=env)
    if result.returncode != 0:
        raise RuntimeError(f"Command failed: {cmd}\nSTDERR: {result.stderr.strip()}")
    return result.stdout.strip()


def gog(args):
    return run(f"{GOG_BIN} {args}", env_extra={"GOG_KEYRING_PASSWORD": GOG_PASSWORD})


def clean(s):
    """Strip newlines, pipes, and extra quotes for safe sheet cell writing."""
    return str(s).replace("\n", " ").replace("\r", " ").replace("|", "/").replace('"', "'").strip()

# ── Step 1: Pull Bee data ─────────────────────────────────────────────────────

def fetch_bee_data():
    log("Fetching Bee data (last 10 hours)...")
    try:
        raw = run("bee now --json")
        data = json.loads(raw)
        log("Bee data retrieved successfully.")
        return data
    except Exception as e:
        log(f"ERROR fetching Bee data: {e}")
        sys.exit(1)

# ── Step 2: Summarize with Gemini (returns clean JSON) ───────────────────────

def summarize_with_gemini(bee_data, label):
    log("Sending to Gemini for summarization...")
    client = genai.Client(api_key=GEMINI_API_KEY)

    bee_text = json.dumps(bee_data, indent=2) if isinstance(bee_data, (dict, list)) else str(bee_data)

    prompt = f"""You are an AI assistant for Acme Services Inc., a commercial property services company.

Below is raw conversation data from a Bee AI wristband worn during a work meeting or discussion.
Meeting label: "{label}"

Return ONLY a valid JSON object with exactly these 4 keys. No markdown, no backticks, no extra text.

{{
  "overview": "2-4 sentence summary of what was discussed.",
  "decisions": "Decisions made, written as a single sentence or list separated by semicolons. If none, write: No formal decisions recorded.",
  "action_items": "Action items, each formatted as: Person - Task - Deadline (if known). Separate multiple items with semicolons. If none, write: No action items recorded.",
  "notes": "Any other relevant context or follow-up topics. If none, write: None."
}}

RAW BEE DATA:
{bee_text}
"""

    try:
        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=prompt
        )
        raw = response.text.strip()

        # Strip markdown fences if Gemini adds them anyway
        if raw.startswith("```"):
            raw = raw.split("```")[1]
            if raw.startswith("json"):
                raw = raw[4:]
        raw = raw.strip()

        parsed = json.loads(raw)
        log("Gemini summary generated successfully.")
        return parsed

    except json.JSONDecodeError as e:
        log(f"ERROR: Gemini did not return valid JSON: {e}")
        log(f"Raw response was: {response.text[:300]}")
        sys.exit(1)
    except Exception as e:
        log(f"ERROR calling Gemini: {e}")
        sys.exit(1)

# ── Step 3: Send email via gog ───────────────────────────────────────────────

def send_email(label, summary, date_str):
    log(f"Sending email to {EMAIL_TO}...")

    subject = f"Meeting Summary - {label} ({date_str})"

    body = f"""Acme Services Inc. — AI Meeting Summary
Generated by Bee Wristband + Gemini AI
Date: {date_str}
Meeting: {label}
{'='*50}

OVERVIEW
{'-'*40}
{summary['overview']}

KEY DECISIONS
{'-'*40}
{chr(10).join(['• ' + d.strip() for d in summary['decisions'].split(';') if d.strip()])}

ACTION ITEMS
{'-'*40}
{chr(10).join(['• ' + a.strip() for a in summary['action_items'].split(';') if a.strip()])}

ADDITIONAL NOTES
{'-'*40}
{summary['notes']}

{'='*50}
This summary was automatically generated from Bee wristband recordings.
"""
    tmp_file = "/tmp/bee_email_body.txt"
    with open(tmp_file, "w") as f:
        f.write(body)

    try:
        cc_flag = f'--cc "{EMAIL_CC}"' if EMAIL_CC else ""
        gog(f'gmail send --to "{EMAIL_TO}" {cc_flag} --subject "{subject}" --body-file {tmp_file} --account {EMAIL_FROM}')
        log("Email sent successfully.")
    except Exception as e:
        log(f"ERROR sending email: {e}")
        log("Continuing to Sheet logging despite email failure.")

# ── Step 4: Log to Google Sheets (one cell at a time) ────────────────────────

def log_to_sheet(label, summary, date_str):
    log(f"Logging to Google Sheet ({SHEET_ID})...")

    # Find the next empty row
    try:
        existing = gog(f'sheets get "{SHEET_ID}" \'{SHEET_TAB}!A:A\' --account {SHEET_ACCOUNT} --json')
        rows = json.loads(existing)
        next_row = max(len(rows) + 1, 2)  # Never overwrite header row 1
    except Exception as e:
        log(f"WARNING: Could not determine next row, using append fallback. {e}")
        row_data = "|".join([
            clean(date_str),
            clean(label),
            clean(summary.get("overview", "N/A")),
            clean(summary.get("decisions", "N/A")),
            clean(summary.get("action_items", "N/A")),
            clean(summary.get("notes", "N/A")),
        ])
        try:
            gog(f'sheets append "{SHEET_ID}" \'{SHEET_TAB}!A:A\' "{row_data}" --account {SHEET_ACCOUNT} --json')
            log("Logged to Google Sheet successfully (append fallback).")
        except Exception as e2:
            log(f"ERROR logging to Sheet: {e2}")
        return

    # Write each cell individually (avoids gog multi-column bug)
    cells = {
        "A": clean(date_str),
        "B": clean(label),
        "C": clean(summary.get("overview", "N/A")),
        "D": clean(summary.get("decisions", "N/A")),
        "E": clean(summary.get("action_items", "N/A")),
        "F": clean(summary.get("notes", "N/A")),
    }

    errors = 0
    for col, value in cells.items():
        cell_ref = f"{SHEET_TAB}!{col}{next_row}"
        try:
            gog(f'sheets update "{SHEET_ID}" \'{cell_ref}\' "{value}" --account {SHEET_ACCOUNT} --json')
        except Exception as e:
            log(f"ERROR writing cell {cell_ref}: {e}")
            errors += 1

    if errors == 0:
        log(f"Logged to Google Sheet successfully (row {next_row}).")
    else:
        log(f"Sheet logging completed with {errors} cell error(s).")

# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="Bee Meeting Summary - Acme Services")
    parser.add_argument("--label", type=str, default="Office Meeting",
                        help="Label for this meeting (e.g. 'Q2 Planning' or 'Site Walk - Building A')")
    args = parser.parse_args()

    date_str = datetime.now().strftime("%Y-%m-%d %I:%M %p")
    label    = args.label

    log("=" * 60)
    log(f"BEE MEETING SUMMARY - {label}")
    log(f"Date: {date_str}")
    log("=" * 60)

    bee_data = fetch_bee_data()
    summary  = summarize_with_gemini(bee_data, label)
    send_email(label, summary, date_str)
    log_to_sheet(label, summary, date_str)

    log("Done. Meeting summary complete.")
    log("=" * 60)


if __name__ == "__main__":
    main()
